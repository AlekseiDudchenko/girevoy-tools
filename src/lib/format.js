// Разбор чисел из полей ввода, общий для всех инструментов. Показ чисел и
// склонения зависят от языка — они в locale.js.

/** Число из поля ввода на любом языке: «81,13» и «81.13» — одно и то же; пустое — NaN. */
export const parseNumber = (raw) => (/^\s*\d+([.,]\d+)?\s*$/.test(raw) ? Number(raw.trim().replace(',', '.')) : NaN);
